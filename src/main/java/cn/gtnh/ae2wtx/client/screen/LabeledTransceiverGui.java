    public void updateList(List<LabelListResponsePacket.Entry> list, String currentLabel, String ownerName,
        String inspectedLabel, int usedChannels, int maxChannels, int onlineCount, int endpointCount,
        int networkChannels, int page, int responsePageSize, int responseTotalEntries, int responsePageCount) {
        pageRequestInFlight = false;
        pageRequestAge = 0;
        // A newer scroll/search request arrived while this one was in flight.
        // Its state is authoritative, so do not briefly render the older page.
        if (queuedPageRequest) {
            sendQueuedPageRequest();
            return;
        }
        pageReceived = true;
        String prevSelected = getSelectedLabel();
        java.util.Set<String> prevSelectedLabels = new java.util.HashSet<>();
        for (int index : selectedIndices) {
            if (index >= 0 && index < filtered.size()) {
                prevSelectedLabels.add(filtered.get(index).label);
            }
        }
        this.entries.clear();
        for (LabelListResponsePacket.Entry e : list) {
            this.entries.add(new Entry(e.label, e.channel));
        }
        this.currentLabel = currentLabel == null ? "" : currentLabel;
        this.currentOwner = ownerName == null ? "" : ownerName;
        this.inspectedLabel = inspectedLabel == null ? "" : inspectedLabel;
        this.showingSelectedBand = LabelNetworkRegistry.normalizeLabel(activeRequestInspectLabel) != null;
        this.onlineCount = onlineCount;
        this.endpointCount = endpointCount;
        this.usedChannels = usedChannels;
        this.maxChannels = maxChannels;
        this.networkChannels = networkChannels;
        this.currentPage = page;
        this.pageSize = responsePageSize;
        this.totalEntries = responseTotalEntries;
        this.pageCount = responsePageCount;
        if (prevSelected != null && !prevSelected.isEmpty()) {
            this.lastSelectedLabel = prevSelected;
        } else if (this.currentLabel != null && !this.currentLabel.isEmpty()) {
            this.lastSelectedLabel = this.currentLabel;
        } else {
            this.lastSelectedLabel = "";
        }
        applyFilter();
        for (int i = 0; i < filtered.size(); i++) {
            if (prevSelectedLabels.contains(filtered.get(i).label)) {
                selectedIndices.add(i);
            }
        }
        int maxOffset = Math.max(0, filtered.size() - VISIBLE_ROWS);
        this.scrollOffset = Math.max(0, Math.min(maxOffset, activeRequestScrollOffset));
        this.activeRequestScrollOffset = 0;
    }

    /* ===================== actions ===================== */

    private void requestList() {
        requestPage(0, 0);
    }

    private void requestPage(int page, int desiredScrollOffset) {
        queuedRequestPage = Math.max(0, page);
        queuedRequestScrollOffset = Math.max(0, desiredScrollOffset);
        queuedRequestQuery = endpointMode ? bandQuery
            : searchBox == null || searchBox.getText() == null ? "" : searchBox.getText();
        queuedRequestInspectLabel = getSelectedLabel();
        if (LabelNetworkRegistry.normalizeLabel(queuedRequestInspectLabel) == null) {
            queuedRequestInspectLabel = lastSelectedLabel == null ? "" : lastSelectedLabel;
        }
        queuedPageRequest = true;
        if (!pageRequestInFlight) {
            sendQueuedPageRequest();
        }
    }

    /** Keep one request in flight and coalesce rapid scrolling/searching to the newest desired page. */
    private void sendQueuedPageRequest() {
        if (!queuedPageRequest) {
            return;
        }
        activeRequestPage = queuedRequestPage;
        activeRequestScrollOffset = queuedRequestScrollOffset;
        activeRequestQuery = queuedRequestQuery;
        activeRequestInspectLabel = queuedRequestInspectLabel;
        queuedPageRequest = false;
        int requestId = ++nextRequestId;
        latestRequestId = requestId;
        pageRequestInFlight = true;
        pageRequestAge = 0;
        NetworkHandler.CHANNEL.sendToServer(
            new LabelListRequestPacket(
                dimension,
                x,
                y,
                z,
                container.windowId,
                requestId,
                activeRequestPage,
                pageSize,
                activeRequestQuery,
                activeRequestInspectLabel));
    }

    /** Reject delayed responses belonging to another block, window, or request. */
    public boolean acceptsResponse(int responseDimension, int responseX, int responseY, int responseZ,
        int responseWindowId, int responseRequestId) {
        return responseDimension == dimension && responseX == x && responseY == y && responseZ == z
            && responseWindowId == container.windowId && responseRequestId == latestRequestId;
    }

    private void sendSet(String label) {
        String normalized = LabelNetworkRegistry.normalizeLabel(label);
        if (normalized == null) {
            return;
        }
        NetworkHandler.CHANNEL
            .sendToServer(new LabelApplyPacket(dimension, x, y, z, container.windowId, normalized));
        this.lastSelectedLabel = normalized;
        this.searchBox.setText("");
        requestPage(0, 0);
    }

    /**
     * Delete every selected band (multi-select: ctrl+click rows). Deleting is
     * irreversible for every transceiver on the band, so the first click only
     * arms the button and a second click on the same selection confirms.
     */
    private void sendDelete() {
        java.util.Set<String> labels = getSelectedLabels();
        if (labels.isEmpty()) {
            return;
        }
        if (!isDeleteArmed() || !labels.equals(deleteArmedLabels)) {
            deleteArmedTicks = DELETE_CONFIRM_TICKS;
            deleteArmedLabels = labels;
            return;
        }
        disarmDelete();
        NetworkHandler.CHANNEL
            .sendToServer(new LabelDeletePacket(dimension, x, y, z, container.windowId, new ArrayList<>(labels)));
        this.lastSelectedLabel = "";
        this.selectedIndices.clear();
        this.selectedIndex = -1;
        requestPage(currentPage, scrollOffset);
    }

    private void sendDisconnect() {
        NetworkHandler.CHANNEL.sendToServer(new LabelApplyPacket(dimension, x, y, z, container.windowId, ""));
        this.lastSelectedLabel = "";
        requestPage(currentPage, scrollOffset);
    }

    private java.util.Set<String> getSelectedLabels() {
        java.util.Set<String> labels = new java.util.LinkedHashSet<>();
        for (int idx : selectedIndices) {
            if (idx >= 0 && idx < filtered.size()) {
                labels.add(filtered.get(idx).label);
            }
        }
        return labels;
    }

    private boolean isDeleteArmed() {
        return deleteArmedTicks > 0;
    }

    private void disarmDelete() {
        deleteArmedTicks = 0;
        deleteArmedLabels = java.util.Collections.emptySet();
    }

    private String getSelectedLabel() {
        if (selectedIndex >= 0 && selectedIndex < filtered.size()) {
            return filtered.get(selectedIndex).label;
        }
        return "";
    }

    private void clearSelectionAndRefresh() {
        if (selectedIndex < 0 && selectedIndices.isEmpty()) {
            return;
        }
        selectedIndex = -1;
        selectedIndices.clear();
        lastSelectedLabel = "";
        requestPage(currentPage, scrollOffset);
    }

    @Override
    protected void actionPerformed(GuiButton button) {
        switch (button.id) {
            case 0: // New
                sendSet(searchBox.getText());
                break;
            case 1: // Delete
                sendDelete();
                break;
            case 2: // Set
                sendSet(getSelectedLabel());
                break;
            case 3: // DC
                sendDisconnect();
                break;
            case 4: // transceivers / back
                toggleEndpointMode();
                break;
            case 5: // Locate
                locate();
                break;
            default:
                break;
        }
    }

    /* ===================== transceiver view ===================== */

    /** The band the info panel shows: the selected one, else this transceiver's own. */
    private String shownLabel() {
        return inspectedLabel.isEmpty() ? currentLabel : inspectedLabel;
    }

    private void toggleEndpointMode() {
        disarmDelete();
        locateOnResponse = false;
        if (endpointMode) {
            endpointMode = false;
            searchBox.setText(bandQuery);
            endpoints.clear();
            endpointFiltered.clear();
            endpointSelected.clear();
            return;
        }
        String label = LabelNetworkRegistry.normalizeLabel(shownLabel());
        if (label == null) {
            return;
        }
        endpointMode = true;
        endpointLabel = label;
        bandQuery = searchBox.getText();
        pendingSearchTicks = -1;
        searchBox.setText("");
        endpoints.clear();
        endpointFiltered.clear();
        endpointSelected.clear();
        endpointScroll = 0;
        endpointReceived = false;
        requestEndpoints();
    }

    private void requestEndpoints() {
        endpointRefreshAge = 0;
        latestEndpointRequestId = ++nextEndpointRequestId;
        NetworkHandler.CHANNEL.sendToServer(new LabelEndpointsRequestPacket(dimension, x, y, z, container.windowId,
            latestEndpointRequestId, endpointLabel));
    }

    /** Reject delayed transceiver lists belonging to another block, window, or request. */
    public boolean acceptsEndpointResponse(int responseDimension, int responseX, int responseY, int responseZ,
        int responseWindowId, int responseRequestId) {
        return responseDimension == dimension && responseX == x && responseY == y && responseZ == z
            && responseWindowId == container.windowId && responseRequestId == latestEndpointRequestId;
    }

    public void updateEndpoints(String label, List<LabelNetworkRegistry.EndpointInfo> list, int total,
        Map<Integer, String> dimensionNames) {
        if (!endpointLabel.equals(label)) {
            return;
        }
        endpointDimNames = new HashMap<>(dimensionNames);
        if (locateOnResponse && !endpointMode) {
            locateOnResponse = false;
            TransceiverLocator.INSTANCE.locate(label, list, total, endpointDimNames);
            mc.thePlayer.closeScreen();
            return;
        }
        if (!endpointMode) {
            return;
        }
        endpointReceived = true;
        endpoints.clear();
        endpoints.addAll(list);
        endpointTotal = total;
        applyEndpointFilter();
    }

    /** Client-side filter over coordinates and dimension names. */
    private void applyEndpointFilter() {
        String query = searchBox.getText() == null ? ""
            : searchBox.getText().trim().toLowerCase(java.util.Locale.ROOT);
        endpointFiltered.clear();
        java.util.Set<String> present = new java.util.HashSet<>();
        for (LabelNetworkRegistry.EndpointInfo e : endpoints) {
            String haystack = (e.x + ", " + e.y + ", " + e.z + " " + e.x + " " + e.y + " " + e.z + " "
                + dimName(e.dim) + " dim " + e.dim).toLowerCase(java.util.Locale.ROOT);
            if (query.isEmpty() || haystack.contains(query)) {
                endpointFiltered.add(e);
                present.add(key(e));
            }
        }
        endpointSelected.retainAll(present);
        endpointScroll = Math.max(0, Math.min(Math.max(0, endpointFiltered.size() - VISIBLE_ROWS), endpointScroll));
    }

    /** Highlight the selected transceivers, or every listed one when none is selected. */
    private void locate() {
        if (!endpointMode) {
            String label = LabelNetworkRegistry.normalizeLabel(shownLabel());
            if (label == null) {
                return;
            }
            endpointLabel = label;
            locateOnResponse = true;
            requestEndpoints();
            return;
        }
        List<LabelNetworkRegistry.EndpointInfo> chosen = new ArrayList<>();
        for (LabelNetworkRegistry.EndpointInfo e : endpointFiltered) {
            if (endpointSelected.isEmpty() || endpointSelected.contains(key(e))) {
                chosen.add(e);
            }
        }
        if (chosen.isEmpty()) {
            return;
        }
        boolean everything = endpointSelected.isEmpty() && chosen.size() == endpoints.size();
        TransceiverLocator.INSTANCE.locate(endpointLabel, chosen, everything ? endpointTotal : chosen.size(),
            endpointDimNames);
        mc.thePlayer.closeScreen();
    }

    private String dimName(int dim) {
        String name = endpointDimNames.get(dim);
        return name == null ? "DIM " + dim : name;
    }

    private static String key(LabelNetworkRegistry.EndpointInfo e) {
        return e.dim + ":" + e.x + ":" + e.y + ":" + e.z;
    }

    private boolean isThisTransceiver(LabelNetworkRegistry.EndpointInfo e) {
        return e.dim == dimension && e.x == x && e.y == y && e.z == z;
    }

    private int distanceTo(LabelNetworkRegistry.EndpointInfo e) {
        return (int) Math.sqrt(player.getDistanceSq(e.x + 0.5D, e.y + 0.5D, e.z + 0.5D));
    }

    private LabelNetworkRegistry.EndpointInfo hoveredEndpoint(int mouseX, int mouseY) {
        if (!endpointMode || !isMouseInList(mouseX, mouseY)) {
            return null;
        }
        int idx = endpointScroll + (mouseY - (guiTop + LIST_Y)) / ROW_H;
        return idx >= 0 && idx < endpointFiltered.size() ? endpointFiltered.get(idx) : null;
    }

    /* ===================== input ===================== */

    @Override
    protected void keyTyped(char typedChar, int keyCode) {
        String before = searchBox.getText();
        if (searchBox.textboxKeyTyped(typedChar, keyCode)) {
            if (!java.util.Objects.equals(before, searchBox.getText())) {
                if (endpointMode) {
                    applyEndpointFilter();
                } else {
                    pendingSearchTicks = 5;
                }
            }
            return;
        }
        super.keyTyped(typedChar, keyCode);
    }

    @Override
    public void updateScreen() {
        super.updateScreen();
        // NetHandlerPlayClient assigns the server window id only after
        // displayGuiScreen/initGui returns. Sending in initGui therefore used
        // window id 0 and the server correctly rejected the first list request.
        if (initialRequestPending && container.windowId != 0) {
            initialRequestPending = false;
            requestList();
        }
        if (pendingSearchTicks > 0 && --pendingSearchTicks == 0) {
            pendingSearchTicks = -1;
            requestPage(0, 0);
        }
        if (pageRequestInFlight && ++pageRequestAge >= PAGE_REQUEST_TIMEOUT_TICKS) {
            pageRequestInFlight = false;
            pageRequestAge = 0;
            if (!queuedPageRequest) {
                queuedRequestPage = activeRequestPage;
                queuedRequestScrollOffset = activeRequestScrollOffset;
                queuedRequestQuery = activeRequestQuery;
                queuedRequestInspectLabel = activeRequestInspectLabel;
                queuedPageRequest = true;
            }
        }
        if (!pageRequestInFlight && queuedPageRequest) {
            sendQueuedPageRequest();
        }
        if (pageRequestInFlight || pendingSearchTicks > 0) {
            autoRefreshAge = 0;
        } else if (!initialRequestPending && ++autoRefreshAge >= AUTO_REFRESH_TICKS) {
            autoRefreshAge = 0;
            requestPage(currentPage, scrollOffset);
        }
        if (endpointMode && ++endpointRefreshAge >= AUTO_REFRESH_TICKS) {
            requestEndpoints();
        }
        if (isDeleteArmed() && (--deleteArmedTicks == 0 || !getSelectedLabels().equals(deleteArmedLabels))) {
            disarmDelete();
        }
        updateActionButtons();
    }

    private void updateActionButtons() {
        boolean validSearch = searchBox != null && LabelNetworkRegistry.normalizeLabel(searchBox.getText()) != null;
        boolean validSelection = LabelNetworkRegistry.normalizeLabel(getSelectedLabel()) != null;
        boolean validShown = LabelNetworkRegistry.normalizeLabel(shownLabel()) != null;
        if (newButton != null) {
            newButton.enabled = !endpointMode && validSearch;
        }
        if (setButton != null) {
            setButton.enabled = !endpointMode && validSelection;
        }
        if (deleteButton != null) {
            deleteButton.enabled = !endpointMode && !selectedIndices.isEmpty();
            deleteButton.armed = isDeleteArmed();
        }
        if (modeButton != null) {
            modeButton.enabled = endpointMode || validShown;
        }
        if (locateButton != null) {
            locateButton.enabled = endpointMode ? !endpointFiltered.isEmpty() : validShown && !locateOnResponse;
        }
        if (disconnectButton != null) {
            disconnectButton.enabled = LabelNetworkRegistry.normalizeLabel(currentLabel) != null;
        }
    }

    @Override
    public void mouseClicked(int mouseX, int mouseY, int mouseButton) {
        super.mouseClicked(mouseX, mouseY, mouseButton);
        searchBox.mouseClicked(mouseX, mouseY, mouseButton);
        if (endpointMode) {
            endpointMouseClicked(mouseX, mouseY);
            return;
        }
        if (isMouseInList(mouseX, mouseY)) {
            int localY = mouseY - (guiTop + LIST_Y);
            int row = localY / ROW_H;
            int idx = scrollOffset + row;
            if (idx >= 0 && idx < filtered.size()) {
                // Windows-style: plain click = single select,
                // ctrl+click = toggle multi-selection
                if (isCtrlKeyDown()) {
                    if (selectedIndices.contains(idx)) {
                        selectedIndices.remove(idx);
                    } else {
                        selectedIndices.add(idx);
                    }
                } else {
                    selectedIndices.clear();
                    selectedIndices.add(idx);
                }
                selectedIndex = idx;
                lastSelectedLabel = filtered.get(idx).label;
                requestPage(currentPage, scrollOffset);
            } else {
                clearSelectionAndRefresh();
            }
        } else if (isMouseInScrollbar(mouseX, mouseY)) {
            updateScrollByMouse(mouseY);
        } else if (!isMouseOverButton(mouseX, mouseY)) {
            // Buttons act on the selection; clicking one (even a disabled
            // one) must not clear it, or Delete could never be confirmed.
            clearSelectionAndRefresh();
        }
    }

    private void endpointMouseClicked(int mouseX, int mouseY) {
        LabelNetworkRegistry.EndpointInfo hit = hoveredEndpoint(mouseX, mouseY);
        if (hit != null) {
            String k = key(hit);
            if (isCtrlKeyDown()) {
                if (!endpointSelected.remove(k)) {
                    endpointSelected.add(k);
                }
            } else {
                endpointSelected.clear();
                endpointSelected.add(k);
            }
        } else if (isMouseInScrollbar(mouseX, mouseY)) {
            updateScrollByMouse(mouseY);
        } else if (!isMouseOverButton(mouseX, mouseY)) {
            endpointSelected.clear();
        }
    }

    @Override
    public void handleMouseInput() {
        super.handleMouseInput();
        int wheel = org.lwjgl.input.Mouse.getEventDWheel();
        if (wheel != 0) {
            int mx = org.lwjgl.input.Mouse.getEventX() * this.width / mc.displayWidth;
            int my = this.height - org.lwjgl.input.Mouse.getEventY() * this.height / mc.displayHeight - 1;
            if (endpointMode && (isMouseInList(mx, my) || isMouseInScrollbar(mx, my))) {
                int maxOffset = Math.max(0, endpointFiltered.size() - VISIBLE_ROWS);
                endpointScroll = Math.max(0, Math.min(maxOffset, endpointScroll + (wheel > 0 ? -1 : 1)));
            } else if (isMouseInList(mx, my) || isMouseInScrollbar(mx, my)) {
                int maxOffset = Math.max(0, filtered.size() - VISIBLE_ROWS);
                if (wheel > 0) {
                    if (scrollOffset > 0) {
                        scrollOffset--;
                    } else if (currentPage > 0) {
                        requestPage(currentPage - 1, Math.max(0, pageSize - VISIBLE_ROWS));
                    }
                } else if (scrollOffset < maxOffset) {
                    scrollOffset++;
                } else if (currentPage + 1 < pageCount) {
                    requestPage(currentPage + 1, 0);
                }
            }
        }
    }

