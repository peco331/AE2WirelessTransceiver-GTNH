    private void renderList(int mouseX, int mouseY) {
        int baseX = guiLeft + LIST_X;
        int baseY = guiTop + LIST_Y;
        if (filtered.isEmpty()) {
            if (pageReceived) {
                String hint = StatCollector.translateToLocal("gui.ae2wtx.labeled_wireless.empty");
                fontRendererObj.drawString(hint, baseX + (LIST_W - fontRendererObj.getStringWidth(hint)) / 2,
                    baseY + 2, 0x808080);
            }
            return;
        }
        int hovered = isMouseInList(mouseX, mouseY) ? scrollOffset + (mouseY - baseY) / ROW_H : -1;
        for (int row = 0; row < VISIBLE_ROWS; row++) {
            int idx = scrollOffset + row;
            if (idx >= filtered.size()) {
                break;
            }
            int y = baseY + row * ROW_H;
            if (selectedIndices.contains(idx)) {
                drawRect(baseX, y, baseX + LIST_W, y + ROW_H, 0xFFB9A3E3);
            } else if (idx == hovered) {
                drawRect(baseX, y, baseX + LIST_W, y + ROW_H, 0x50FFFFFF);
            }
            String label = filtered.get(idx).label;
            boolean current = label.equals(currentLabel);
            if (current) {
                // marker bar for the band this transceiver is on
                drawRect(baseX, y + 1, baseX + 2, y + ROW_H - 1, 0xFF2E7D32);
            }
            String text = fontRendererObj.trimStringToWidth(label, LIST_W - 6);
            int ty = y + (ROW_H - fontRendererObj.FONT_HEIGHT) / 2 + 1;
            fontRendererObj.drawString(text, baseX + 4, ty, current ? 0x1B5E20 : 0x303030);
        }
    }

    /** Transceiver rows: online dot, coordinates, and the distance or the dimension on the right. */
    private void renderEndpointList(int mouseX, int mouseY) {
        int baseX = guiLeft + LIST_X;
        int baseY = guiTop + LIST_Y;
        if (endpointFiltered.isEmpty()) {
            if (endpointReceived) {
                String hint = fontRendererObj.trimStringToWidth(
                    StatCollector.translateToLocal("gui.ae2wtx.labeled_wireless.endpoints_empty"), LIST_W - 4);
                fontRendererObj.drawString(hint, baseX + (LIST_W - fontRendererObj.getStringWidth(hint)) / 2,
                    baseY + 2, 0x808080);
            }
            return;
        }
        LabelNetworkRegistry.EndpointInfo hovered = hoveredEndpoint(mouseX, mouseY);
        for (int row = 0; row < VISIBLE_ROWS; row++) {
            int idx = endpointScroll + row;
            if (idx >= endpointFiltered.size()) {
                break;
            }
            LabelNetworkRegistry.EndpointInfo e = endpointFiltered.get(idx);
            int y = baseY + row * ROW_H;
            if (endpointSelected.contains(key(e))) {
                drawRect(baseX, y, baseX + LIST_W, y + ROW_H, 0xFFB9A3E3);
            } else if (e == hovered) {
                drawRect(baseX, y, baseX + LIST_W, y + ROW_H, 0x50FFFFFF);
            }
            boolean self = isThisTransceiver(e);
            if (self) {
                // marker bar for the transceiver this GUI belongs to
                drawRect(baseX, y + 1, baseX + 2, y + ROW_H - 1, 0xFF2E7D32);
            }
            drawRect(baseX + 4, y + 4, baseX + 7, y + 7, e.online ? 0xFF3FBF3F : 0xFF7A7A7A);
            int ty = y + (ROW_H - fontRendererObj.FONT_HEIGHT) / 2 + 1;
            String right = fontRendererObj.trimStringToWidth(
                e.dim == dimension ? distanceTo(e) + "m" : dimName(e.dim), 48);
            int rightW = fontRendererObj.getStringWidth(right);
            fontRendererObj.drawString(right, baseX + LIST_W - 2 - rightW, ty, 0x707070);
            String coords = fontRendererObj.trimStringToWidth(e.x + ", " + e.y + ", " + e.z, LIST_W - 15 - rightW);
            fontRendererObj.drawString(coords, baseX + 10, ty, self ? 0x1B5E20 : 0x303030);
        }
    }

    /** Band info panel: the selected band, or this transceiver's band when nothing is selected. */
    private void drawInfo(float scale) {
        String displayLabel = inspectedLabel.isEmpty() ? currentLabel : inspectedLabel;
        String headerKey = showingSelectedBand ? "gui.ae2wtx.labeled_wireless.selected_label"
            : "gui.ae2wtx.labeled_wireless.current_label";
        boolean isCurrent = !displayLabel.isEmpty() && displayLabel.equals(currentLabel);
        String ownerLine = StatCollector.translateToLocal("gui.ae2wtx.labeled_wireless.current_owner") + ": "
            + (currentOwner.isEmpty() ? StatCollector.translateToLocal("ae2wtx.waila.owner.public") : currentOwner);
        String onlineLine = StatCollector.translateToLocal("gui.ae2wtx.labeled_wireless.online_count") + ": " + onlineCount;
        boolean inspectingOtherBand = showingSelectedBand && !displayLabel.equals(currentLabel);
        String channelLine = inspectingOtherBand
            ? StatCollector.translateToLocal("gui.ae2wtx.labeled_wireless.endpoint_count") + ": " + endpointCount
            : maxChannels <= 0
                ? StatCollector.translateToLocalFormatted("ae2wtx.waila.channels", usedChannels)
                : StatCollector.translateToLocalFormatted("ae2wtx.waila.channels_of", usedChannels, maxChannels);
        // whole-frequency (label) usage across ALL endpoints; denominator is the
        // real capacity granted by the ME network (32 dense, infinite in infinite mode)
        boolean infinite = maxChannels <= 0 || maxChannels >= 1_000_000;
        String networkPrefix = StatCollector.translateToLocal("ae2wtx.waila.channels_network_label");
        String networkValue;
        int networkColor = 0x404040;
        if (infinite) {
            networkValue = networkChannels + "/∞";
        } else {
            networkValue = networkChannels + "/" + maxChannels;
            // over capacity -> red, exactly full -> amber
            if (networkChannels > maxChannels) {
                networkColor = 0xC03030;
            } else if (networkChannels == maxChannels) {
                networkColor = 0xA07000;
            }
        }
        // header and band name above the separator baked into the texture, details below
        drawScaledText(trim(StatCollector.translateToLocal(headerKey)), INFO_X, INFO_Y, scale, 0x707070);
        drawScaledText(trim(displayLabel.isEmpty() ? "-" : displayLabel), INFO_X, INFO_Y + 10, scale,
            isCurrent ? 0x1B5E20 : 0x202020);
        drawScaledText(trim(ownerLine), INFO_X, INFO_Y + 25, scale, 0x404040);
        drawScaledText(trim(onlineLine), INFO_X, INFO_Y + 35, scale, 0x404040);
        drawScaledText(trim(channelLine), INFO_X, INFO_Y + 45, scale, 0x404040);
        drawScaledText(trim(networkPrefix), INFO_X, INFO_Y + 55, scale, 0x404040);
        drawScaledText(trim(networkValue), INFO_X + (int) (fontRendererObj.getStringWidth(networkPrefix) * scale),
            INFO_Y + 55, scale, networkColor);
    }

    private String trim(String text) {
        int maxWidth = (int) (INFO_MAX_WIDTH / Math.max(0.0001F, getScale()));
        return fontRendererObj.trimStringToWidth(text, maxWidth);
    }

    private void drawScaledText(String text, int x, int y, float scale, int color) {
        GL11.glPushMatrix();
        GL11.glTranslatef(x, y, 0);
        GL11.glScalef(scale, scale, 1.0F);
        fontRendererObj.drawString(text, 0, 0, color);
        GL11.glPopMatrix();
    }

    private void renderScrollBar() {
        int knobX = guiLeft + SCROLL_X;
        if (endpointMode) {
            int total = endpointFiltered.size();
            if (total <= VISIBLE_ROWS) {
                drawKnob(knobX, guiTop + SCROLL_Y, 15, false);
                return;
            }
            int knobH = Math.max(10, (int) ((double) VISIBLE_ROWS / total * SCROLL_H));
            int knobY = guiTop + SCROLL_Y
                + (int) ((SCROLL_H - knobH) * (endpointScroll / (double) (total - VISIBLE_ROWS)));
            drawKnob(knobX, knobY, knobH, true);
            return;
        }
        int total = totalEntries;
        if (total <= VISIBLE_ROWS) {
            drawKnob(knobX, guiTop + SCROLL_Y, 15, false);
            return;
        }
        int maxOffset = Math.max(1, total - VISIBLE_ROWS);
        int knobH = Math.max(10, (int) ((double) VISIBLE_ROWS / total * SCROLL_H));
        int globalOffset = Math.min(maxOffset, currentPage * pageSize + scrollOffset);
        int knobY = guiTop + SCROLL_Y + (int) ((SCROLL_H - knobH) * (globalOffset / (double) maxOffset));
        drawKnob(knobX, knobY, knobH, true);
    }

    /** Raised AE2-style knob; greyed out when the list does not scroll. */
    private void drawKnob(int x0, int y0, int h, boolean active) {
        int x1 = x0 + SCROLL_W;
        int y1 = y0 + h;
        drawRect(x0, y0, x1, y1, active ? 0xFF555555 : 0xFF6E6E6E);
        drawRect(x0, y0, x1 - 1, y1 - 1, active ? 0xFFFFFFFF : 0xFF9A9A9A);
        drawRect(x0 + 1, y0 + 1, x1 - 1, y1 - 1, active ? 0xFFC6C6C6 : 0xFF828282);
    }

    private boolean isMouseInList(int mouseX, int mouseY) {
        return mouseX >= guiLeft + LIST_X && mouseX < guiLeft + LIST_X + LIST_W
            && mouseY >= guiTop + LIST_Y && mouseY < guiTop + LIST_Y + LIST_H;
    }

    private boolean isMouseOverButton(int mouseX, int mouseY) {
        for (Object o : buttonList) {
            GuiButton b = (GuiButton) o;
            if (b.visible && mouseX >= b.xPosition && mouseY >= b.yPosition && mouseX < b.xPosition + b.width
                && mouseY < b.yPosition + b.height) {
                return true;
            }
        }
        return false;
    }

    private boolean isMouseInScrollbar(int mouseX, int mouseY) {
        return mouseX >= guiLeft + SCROLL_X && mouseX < guiLeft + SCROLL_X + SCROLL_W
            && mouseY >= guiTop + SCROLL_Y && mouseY < guiTop + SCROLL_Y + SCROLL_H;
    }

    private void updateScrollByMouse(int mouseY) {
        if (endpointMode) {
            int total = endpointFiltered.size();
            if (total <= VISIBLE_ROWS) {
                return;
            }
            int knobH = Math.max(10, (int) ((double) VISIBLE_ROWS / total * SCROLL_H));
            double ratio = (mouseY - (guiTop + SCROLL_Y) - knobH / 2.0D) / (double) (SCROLL_H - knobH);
            ratio = Math.max(0.0D, Math.min(1.0D, ratio));
            endpointScroll = (int) Math.round(ratio * (total - VISIBLE_ROWS));
            return;
        }
        int total = totalEntries;
        if (total <= VISIBLE_ROWS) {
            return;
        }
        int maxOffset = Math.max(0, total - VISIBLE_ROWS);
        int relativeY = mouseY - (guiTop + SCROLL_Y);
        relativeY = Math.max(0, Math.min(SCROLL_H, relativeY));
        int knobH = Math.max(10, (int) ((double) VISIBLE_ROWS / total * SCROLL_H));
        double ratio = (relativeY - knobH / 2.0D) / (double) (SCROLL_H - knobH);
        ratio = Math.max(0.0D, Math.min(1.0D, ratio));
        int globalOffset = (int) Math.round(ratio * maxOffset);
        // A page only has (pageSize - visibleRows) valid first-row offsets.
        // Map the otherwise unreachable gap at each page boundary to the next
        // page, so a short final page (for example item 65 of 65) remains
        // reachable by dragging the scrollbar all the way down.
        int safePageSize = Math.max(1, pageSize);
        int requestedPage = Math.min(pageCount - 1, (globalOffset + VISIBLE_ROWS - 1) / safePageSize);
        int requestedLocalOffset = Math.max(0, globalOffset - requestedPage * safePageSize);
        if (requestedPage == currentPage) {
            scrollOffset = Math.max(0, Math.min(Math.max(0, filtered.size() - VISIBLE_ROWS), requestedLocalOffset));
        } else {
            requestPage(requestedPage, requestedLocalOffset);
        }
    }

    private void applyFilter() {
        filtered.clear();
        filtered.addAll(entries);
        scrollOffset = 0;
        selectedIndex = -1;
        selectedIndices.clear();
        if (lastSelectedLabel != null && !lastSelectedLabel.isEmpty()) {
            for (int i = 0; i < filtered.size(); i++) {
                if (filtered.get(i).label.equals(lastSelectedLabel)) {
                    selectedIndex = i;
                    ensureSelectionVisible();
                    break;
                }
            }
        }
    }

    private void ensureSelectionVisible() {
        if (selectedIndex < 0) {
            return;
        }
        int maxOffset = Math.max(0, filtered.size() - VISIBLE_ROWS);
        if (selectedIndex < scrollOffset) {
            scrollOffset = selectedIndex;
        } else if (selectedIndex >= scrollOffset + VISIBLE_ROWS) {
            scrollOffset = Math.min(maxOffset, selectedIndex - VISIBLE_ROWS + 1);
        }
    }

    private boolean isEnglish() {
        Minecraft mc = Minecraft.getMinecraft();
        return mc.getLanguageManager() != null && mc.getLanguageManager().getCurrentLanguage() != null
            && "en_US".equals(mc.getLanguageManager().getCurrentLanguage().getLanguageCode());
    }

    private float getScale() {
        return isEnglish() ? 0.75F : 1.0F;
    }

